def test_question(question, session_id="test_session"):
    """测试单个问题"""
    try:
        response = requests.post(
            'http://localhost:8000/api/chat',
            json={
                'message': question,
                'session_id': session_id,
                'user_id': 'test_user'
            },
            timeout=30
        )
        result = response.json()
        return {
            'question': question,
            'answer': result.get('answer', ''),
            'type': result.get('type', 'unknown'),
            'sources': result.get('sources'),
            'success': True
        }
    except Exception as e:
        return {
            'question': question,
            'error': str(e),
            'success': False
        }

def main():
    print("=" * 60)
    print("校园百事通系统测试 - 200个问题")
    print(f"开始时间: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("=" * 60)

    results = []
    total = 0
    success = 0
    failed = 0

    for category, questions in TEST_QUESTIONS.items():
        print(f"\n【{category}】测试中...")
        category_success = 0

        for i, question in enumerate(questions, 1):
            total += 1
            result = test_question(question)
            results.append(result)

            if result['success']:
                success += 1
                category_success += 1
                answer_preview = result['answer'][:50] + "..." if len(result['answer']) > 50 else result['answer']
                print(f"  [{i}/10] OK {question[:20]}... -> {result['type']}")
            else:
                failed += 1
                print(f"  [{i}/10] FAIL {question[:20]}... -> 错误: {result.get('error', 'Unknown')}")

            time.sleep(0.5)  # 避免请求过快

        print(f"  类别完成: {category_success}/10 成功")

    print("\n" + "=" * 60)
    print("测试结果汇总")
    print("=" * 60)
    print(f"总问题数: {total}")
    print(f"成功: {success}")
    print(f"失败: {failed}")
    print(f"成功率: {success/total*100:.1f}%")
    print(f"结束时间: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

    # 统计回答类型
    type_counts = {}
    for r in results:
        if r['success']:
            t = r.get('type', 'unknown')
            type_counts[t] = type_counts.get(t, 0) + 1

    print("\n回答类型分布:")
    for t, count in sorted(type_counts.items(), key=lambda x: -x[1]):
        print(f"  {t}: {count}")

    # 保存详细结果
    with open('test_results.json', 'w', encoding='utf-8') as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print("\n详细结果已保存到 test_results.json")

if __name__ == "__main__":
    main()
